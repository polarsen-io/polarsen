-- Description: Create batch jobs tracking table

CREATE TABLE IF NOT EXISTS general.batch_jobs
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_type      TEXT        NOT NULL CONSTRAINT job_type_valid CHECK (LENGTH(job_type) < 100),
    status        TEXT        NOT NULL DEFAULT 'pending' CONSTRAINT status_valid CHECK (status IN ('pending', 'running', 'completed', 'failed', 'cancelled')),
    user_id       BIGINT      NOT NULL REFERENCES general.users,
    model_name    TEXT CONSTRAINT model_name_valid CHECK (LENGTH(model_name) < 200),
    model_source  TEXT CONSTRAINT model_source_valid CHECK (model_source IN ('mistral', 'gemini', 'openai', 'grok')),
    run_id        UUID,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    started_at    TIMESTAMPTZ,
    completed_at  TIMESTAMPTZ,
    error_message TEXT CONSTRAINT error_message_valid CHECK (LENGTH(error_message) < 10000),
    progress      INT         NOT NULL DEFAULT 0,
    total_items   INT,
    meta          JSONB,

    CONSTRAINT started_at_valid CHECK (started_at IS NULL OR started_at >= created_at),
    CONSTRAINT completed_at_valid CHECK (completed_at IS NULL OR completed_at >= started_at),
    CONSTRAINT progress_valid CHECK (progress >= 0 AND (total_items IS NULL OR progress <= total_items))
);

CREATE INDEX IF NOT EXISTS batch_jobs_user_id_idx ON general.batch_jobs (user_id);
CREATE INDEX IF NOT EXISTS batch_jobs_status_idx ON general.batch_jobs (status);
CREATE INDEX IF NOT EXISTS batch_jobs_job_type_idx ON general.batch_jobs (job_type);
CREATE INDEX IF NOT EXISTS batch_jobs_run_id_idx ON general.batch_jobs (run_id) WHERE run_id IS NOT NULL;